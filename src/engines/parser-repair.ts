// src/engines/parser-repair.ts
// Unit U3 — Low-confidence streaming parser repair loop.
//
// StreamParserEngine deparses a raw provider stream into ContentBlock[]. When confidence
// is below threshold the pipeline must *reparse* with a better parser rather than give up.
// This module regenerates an inline ParserModule (deterministic template by default; a
// pluggable "research" generator for the LLM-backed path) and upserts it as the active
// parser for the provider, then re-parses. Closing the loop: deparse → low confidence →
// regenerate → reparse.

import { createHash } from 'node:crypto'
import type { ParserStore, ProviderParserRow } from '../storage/contracts/parser-store.js'
import type { StreamParserEngine } from './stream-parser.js'

export interface RepairReport {
  providerId: string
  repaired: boolean
  beforeConfidence: number
  afterConfidence: number
  parserName: string
  reason: string
}

export type ParserRepairer = (providerId: string, rawBody: string) => string

/**
 * Deterministic fallback ParserModule source for a provider. CommonJS shape expected
 * by StreamParserEngine.loadInlineParser (module.exports). Splits the raw body into
 * lines; if it looks like NDJSON it classifies each line, otherwise emits text blocks.
 */
export const generateParserModuleCode: ParserRepairer = (providerId, rawBody) => {
  const sample = rawBody.split('\n').slice(0, 20).join('\n')
  const prefersJson = sample.split('\n').filter((l) => l.trim() && safeJson(l)).length > 2
  return `// Auto-repaired parser for ${providerId} (generated by parser-repair)
const PREFERS_JSON = ${prefersJson ? 'true' : 'false'}
function parse(rawBody) {
  const lines = String(rawBody).split('\\n').filter((l) => l.trim().length > 0)
  const blocks = []
  let i = 0
  for (const line of lines) {
    if (PREFERS_JSON) {
      try {
        const obj = JSON.parse(line)
        if (obj && obj.type === 'tool_use') blocks.push({ kind: 'tool_use', toolName: obj.name, input: obj.input || {}, index: i })
        else if (obj && obj.type) blocks.push({ kind: String(obj.type), content: line, index: i })
        else blocks.push({ kind: 'meta', key: 'json', value: obj, index: i })
        i++
        continue
      } catch {}
    }
    blocks.push({ kind: 'text', content: line, index: i })
    i++
  }
  return blocks
}
function detectCompletion(rawBody) {
  const s = String(rawBody)
  return s.trim().endsWith('[DONE]') || !s.includes('"partial"')
}
function getConfidence() { return 0.85 }
module.exports = { name: 'repair-${providerId}', version: 1, providerId: ${JSON.stringify(providerId)}, parse, detectCompletion, getConfidence }
`
}

function safeJson(s: string): boolean {
  try {
    JSON.parse(s)
    return true
  } catch {
    return false
  }
}

export interface RepairOptions {
  minConfidence?: number
  generateCode?: ParserRepairer
}

/**
 * Repair a provider's parser when confidence is low. Returns a report; idempotent in
 * effect (a regeneration only happens when the first parse is below threshold).
 */
export async function repairLowConfidenceParser(
  engine: Pick<StreamParserEngine, 'parse' | 'reloadParser'>,
  store: ParserStore,
  providerId: string,
  rawBody: string,
  opts: RepairOptions = {},
): Promise<RepairReport> {
  const minConfidence = opts.minConfidence ?? 0.7
  const generate = opts.generateCode ?? generateParserModuleCode

  const first = await engine.parse(rawBody, providerId)
  const before = first.confidence
  if (before >= minConfidence) {
    return {
      providerId,
      repaired: false,
      beforeConfidence: before,
      afterConfidence: before,
      parserName: first.parserName,
      reason: 'confidence above threshold',
    }
  }

  const code = generate(providerId, rawBody)
  const hash = createHash('sha256').update(code).digest('hex').slice(0, 16)
  const now = Date.now()
  const row: ProviderParserRow = {
    id: `parser:repair:${providerId}:${hash}`,
    providerId,
    name: `repair-${providerId}`,
    version: 1,
    logicType: 'inline',
    filePath: null,
    logicCode: code,
    hash,
    isActive: 1,
    fallbackParserId: null,
    createdAt: now,
    updatedAt: now,
  }
  await store.upsertParser(row)
  await engine.reloadParser(providerId)

  const second = await engine.parse(rawBody, providerId)
  return {
    providerId,
    repaired: true,
    beforeConfidence: before,
    afterConfidence: second.confidence,
    parserName: second.parserName,
    reason: 'regenerated inline parser below confidence threshold',
  }
}
