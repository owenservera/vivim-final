  async assignConversation(
    conversationId: string,
    topicId: string,
    assignmentType: 'auto' | 'manual' = 'auto',
    confidence = 0.5,
  ): Promise<void> {
    const now = Date.now()
    await this.db.prisma.conversationTopic.upsert({
      where: {
        conversationId_topicId: { conversationId, topicId },
      },
      create: {
        id: newId(),
        conversationId,
        topicId,
        confidence,
        assignedAt: now,
        assignedBy: assignmentType,
      },
      update: {
        confidence,
        assignedAt: now,
        assignedBy: assignmentType,
      },
    })
    await this.db.prisma.topic.update({
      where: { id: topicId },
      data: {
        conversationCount: { increment: 1 },
        updatedAt: now,
      },
    })
  }

