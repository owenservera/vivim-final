  // ═══════════════════════════════════════════════════════════════════════
  // Entity
  // ═══════════════════════════════════════════════════════════════════════

  async createEntity(input: {
    name: string
    type: string
    description?: string
    confidence?: number
  }): Promise<EntityRow> {
    const now = Date.now()
    const row = await this.db.prisma.entity.create({
      data: {
        id: newId(),
        name: input.name,
        type: input.type,
        description: input.description ?? null,
        confidence: input.confidence ?? 0.5,
        mentionCount: 0,
        firstSeenAt: now,
        lastSeenAt: now,
        createdAt: now,
        updatedAt: now,
      },
    })
    return this.toEntityRow(row)
  }

  async getEntityById(id: string): Promise<EntityRow | null> {
    const row = await this.db.prisma.entity.findUnique({ where: { id } })
    return row ? this.toEntityRow(row) : null
  }

  async listEntities(filter?: EntityFilter): Promise<EntityRow[]> {
    const where: Record<string, unknown> = {}
    if (filter?.type) where.type = filter.type
    if (filter?.name) where.name = filter.name
    const rows = await this.db.prisma.entity.findMany({
      where,
      orderBy: { updatedAt: 'desc' },
      take: filter?.limit ?? 100,
      skip: filter?.offset ?? 0,
    })
    return rows.map((r) => this.toEntityRow(r))
  }

  async updateEntity(
    id: string,
    patch: Partial<Pick<EntityRow, 'name' | 'type' | 'description' | 'confidence'>>,
  ): Promise<EntityRow> {
    const now = Date.now()
    const row = await this.db.prisma.entity.update({
      where: { id },
      data: {
        ...patch,
        updatedAt: now,
      },
    })
    return this.toEntityRow(row)
  }

  async softDeleteEntity(id: string): Promise<void> {
    const now = Date.now()
    await this.db.prisma.entity.update({
      where: { id },
      data: { confidence: 0, updatedAt: now },
    })
  }

  async findByType(type: string): Promise<EntityRow[]> {
    const rows = await this.db.prisma.entity.findMany({
      where: { type },
      orderBy: { mentionCount: 'desc' },
    })
    return rows.map((r) => this.toEntityRow(r))
  }

  async findByName(name: string): Promise<EntityRow | null> {
    const row = await this.db.prisma.entity.findFirst({ where: { name } })
    return row ? this.toEntityRow(row) : null
  }

  async incrementMentionCount(id: string): Promise<void> {
    const now = Date.now()
    await this.db.prisma.entity.update({
      where: { id },
      data: {
        mentionCount: { increment: 1 },
        lastSeenAt: now,
        updatedAt: now,
      },
    })
  }

  private toEntityRow(r: any): EntityRow {
    return {
      id: r.id as string,
      name: r.name as string,
      type: r.type as string,
      description: r.description as string | null,
      confidence: r.confidence as number,
      mentionCount: r.mentionCount as number,
      firstSeenAt: Number(r.firstSeenAt),
      lastSeenAt: Number(r.lastSeenAt),
      createdAt: Number(r.createdAt),
      updatedAt: Number(r.updatedAt),
    }
  }

